import { IntakeAnalysis, RiskAssessment, RiskLevel } from '../types.js';

export function runRiskAgent(intake: IntakeAnalysis): RiskAssessment {
  let riskLevel: RiskLevel = 'LOW';
  let score = 20;
  const primaryFactors: string[] = [];
  const uncertainties: string[] = [...intake.missingInformation];

  switch (intake.reportedHazard) {
    case 'suspected_gas_leak':
      primaryFactors.push('Volatile flammable gas presence indicated by sulfur/mercaptan odor');
      if (intake.symptoms.length > 0) {
        riskLevel = 'CRITICAL';
        score = 95;
        primaryFactors.push(
          `Acute physical distress detected: ${intake.symptoms.join(', ')}. Indicates dangerous ambient concentration.`
        );
      } else {
        riskLevel = 'HIGH';
        score = 82;
        primaryFactors.push('Unconfirmed ambient concentration; high deflagration threat potential.');
      }
      break;

    case 'smoke_fire':
      riskLevel = 'CRITICAL';
      score = 90;
      primaryFactors.push('Active combustion or pyrolytic smoke reported; rapid thermal spread risk.');
      if (intake.symptoms.length > 0) {
        primaryFactors.push(`Inhalation symptoms present: ${intake.symptoms.join(', ')}.`);
      }
      break;

    case 'medical_distress':
      riskLevel = 'HIGH';
      score = 85;
      primaryFactors.push('Severe human physiological emergency requiring immediate EMS intervention.');
      break;

    case 'electrical_hazard':
      riskLevel = 'HIGH';
      score = 75;
      primaryFactors.push('Live conductor or arcing risk with potential for thermal transition to fire.');
      break;

    case 'benign_or_unknown':
    default:
      riskLevel = 'LOW';
      score = 15;
      primaryFactors.push('Report lacks indicators of acute domestic hazard, explosive gas, or fire.');
      break;
  }

  // Uncertainties
  if (!intake.hasSensorConfirmation) {
    uncertainties.unshift('Absence of calibrated hardware sensor confirmation; relies on subjective human sensory report.');
  }

  let recommendedPosture = 'IMMEDIATE LIFE-SAFETY EVACUATION & SAFE-PERIMETER ISOLATION';
  if ((riskLevel as RiskLevel) === 'LOW') {
    recommendedPosture = 'OBSERVATION & ROUTINE VERIFICATION';
  } else if ((riskLevel as RiskLevel) === 'MODERATE') {
    recommendedPosture = 'PRECAUTIONARY VENTILATION & SENSOR MONITORING';
  }

  return {
    riskLevel,
    hazard: intake.reportedHazard,
    confidence: intake.hasSensorConfirmation ? 0.95 : 0.85,
    score,
    primaryFactors,
    uncertainties,
    recommendedPosture,
    isSimulatedAssessment: true,
    assessedAt: new Date().toISOString(),
    disclaimer:
      'SIMULATION NOTICE: This risk assessment is generated by rule-based emergency triage intelligence for demonstration and simulation purposes only. It is NOT a certified industrial gas safety or clinical medical diagnostic system.',
  };
}
